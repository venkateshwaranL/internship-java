package in.sp.stringstack.oops.aggregation_composition;

public class Brain {
    private String color;
    private float weight;

    public Brain(String color, float weight) {
        this.color = color;
        this.weight = weight;
    }

    public String getColor() {
        return color;
    }

    public float getWeight() {
        return weight;
    }
}
